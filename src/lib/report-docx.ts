/* The Word renderer.

   Word is what institutions actually want: a PDF is final, but a .docx can be
   pasted into the college's own letterhead and edited before it is filed.

   Built with the `docx` package rather than hand-written XML. The Android app
   writes OOXML by hand because adding a library to an APK costs megabytes; in
   a browser that trade-off does not apply, and a library that understands
   sections and image relationships is less likely to produce a file Word
   refuses to open. */
import {
  AlignmentType, BorderStyle, Document, HeadingLevel, ImageRun, Packer,
  Paragraph, Table, TableCell, TableRow, TextRun, WidthType,
} from 'docx';
import { dateRange, formatDateTime, particulars, sections, type Report } from './report';

export async function buildDocx(report: Report): Promise<Blob> {
  const f = report.fields;
  const t = report.template;
  const children: (Paragraph | Table)[] = [];

  if (t.letterheadDataUrl) {
    const image = await imageRun(t.letterheadDataUrl, 560);
    if (image) children.push(new Paragraph({ children: [image], alignment: AlignmentType.CENTER }));
  }

  if (t.includeCover) {
    children.push(
      centred(f.institutionName, 32, true),
      centred(f.institutionUniversity, 22),
      centred(f.institutionAddress, 18),
    );
    if (f.department) children.push(centred(`Department of ${f.department}`, 22, true));
    children.push(
      new Paragraph({ text: '' }),
      centred('ACTIVITY REPORT', 24, true),
      centred(f.title, 30, true),
      centred(f.subtitle, 22),
      centred(f.eventType, 20),
      centred(dateRange(report), 20),
      centred(f.venue, 18),
      new Paragraph({ children: [], pageBreakBefore: false }),
    );
  }

  if (t.includeParticulars) {
    const rows = particulars(report);
    if (rows.length) {
      children.push(new Paragraph({ text: 'Particulars', heading: HeadingLevel.HEADING_1 }));
      children.push(new Table({
        width: { size: 100, type: WidthType.PERCENTAGE },
        borders: grey(),
        rows: rows.map((row) => new TableRow({
          children: [
            new TableCell({ width: { size: 32, type: WidthType.PERCENTAGE }, children: [bold(row.label)] }),
            new TableCell({ width: { size: 68, type: WidthType.PERCENTAGE }, children: [plain(row.value)] }),
          ],
        })),
      }));
      children.push(new Paragraph({ text: '' }));
    }
  }

  if (t.includeWriteUp) {
    sections(report).forEach((section) => {
      children.push(new Paragraph({ text: section.heading, heading: HeadingLevel.HEADING_2 }));
      // Blank lines are paragraph breaks; a pasted write-up keeps its shape.
      section.body.split('\n').forEach((line) => children.push(plain(line)));
      children.push(new Paragraph({ text: '' }));
    });
  }

  if (t.includePhotos) {
    const withImages = report.photos.filter((photo) => photo.dataUrl);
    if (withImages.length) {
      children.push(new Paragraph({ text: 'Photographs', heading: HeadingLevel.HEADING_1, pageBreakBefore: true }));
      const width = t.photosPerPage >= 4 ? 250 : 430;
      for (let index = 0; index < withImages.length; index += 1) {
        const photo = withImages[index];
        const image = await imageRun(photo.dataUrl as string, width);
        if (image) {
          children.push(new Paragraph({ children: [image], alignment: AlignmentType.CENTER }));
        }
        children.push(centred(`Photograph ${index + 1}`, 17, true));
        if (photo.takenAt) children.push(centred(formatDateTime(photo.takenAt), 16));
        children.push(new Paragraph({ text: '' }));
      }
    }
  }

  if (t.includeAnnexure && report.photos.length) {
    children.push(new Paragraph({ text: 'Annexure - photograph index', heading: HeadingLevel.HEADING_1, pageBreakBefore: true }));
    children.push(new Table({
      width: { size: 100, type: WidthType.PERCENTAGE },
      borders: grey(),
      rows: report.photos.map((photo, index) => new TableRow({
        children: [
          new TableCell({ width: { size: 8, type: WidthType.PERCENTAGE }, children: [plain(String(index + 1))] }),
          new TableCell({ width: { size: 57, type: WidthType.PERCENTAGE }, children: [plain(photo.name)] }),
          new TableCell({ width: { size: 35, type: WidthType.PERCENTAGE }, children: [plain(photo.takenAt ? formatDateTime(photo.takenAt) : '')] }),
        ],
      })),
    }));
  }

  children.push(new Paragraph({ text: '' }));
  children.push(new Paragraph({
    children: [new TextRun({
      text: `Generated by Geo Snap - NLR on ${formatDateTime(new Date().toISOString())} from ${report.photos.length} geo-tagged photograph(s).`,
      italics: true, size: 15,
    })],
  }));

  const document = new Document({ sections: [{ children }] });
  return await Packer.toBlob(document);
}

function centred(text: string, size: number, bold = false): Paragraph {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    children: [new TextRun({ text: text || '', bold, size })],
  });
}

function plain(text: string): Paragraph {
  return new Paragraph({ children: [new TextRun({ text: text || '', size: 21 })] });
}

function bold(text: string): Paragraph {
  return new Paragraph({ children: [new TextRun({ text: text || '', bold: true, size: 19 })] });
}

function grey() {
  const side = { style: BorderStyle.SINGLE, size: 4, color: 'BFBFBF' };
  return { top: side, bottom: side, left: side, right: side, insideHorizontal: side, insideVertical: side };
}

/**
 * Word needs the pixel size declared up front, so the natural ratio is read
 * before the image is placed; a wrong ratio stretches the photograph.
 */
async function imageRun(dataUrl: string, width: number): Promise<ImageRun | null> {
  try {
    const ratio = await new Promise<number>((resolve) => {
      const image = new Image();
      image.onload = () => resolve(image.width / Math.max(1, image.height));
      image.onerror = () => resolve(4 / 3);
      image.src = dataUrl;
    });
    const response = await fetch(dataUrl);
    const buffer = await response.arrayBuffer();
    return new ImageRun({
      data: buffer,
      transformation: { width, height: Math.round(width / ratio) },
      type: 'jpg',
    });
  } catch {
    return null;
  }
}
